"""Bundled example datasets, one for every mineral.

Each entry records where the data came from.  Two kinds are shipped:

**measured**
    Published data, taken from the paper's supplementary tables and cited.
    Use these to check Diffusor against a published timescale.  The interface
    does not label them; only synthetic data carry a label.

**synthetic**
    Generated by Diffusor's own forward model with a known time, then given
    Gaussian noise.  The *conditions* are taken from a real published study of
    the same mineral so the numbers are realistic, but the profile itself is
    not a measurement.  Every synthetic entry says so explicitly, in this
    catalogue, in the loader and in the exported methods block.

Nothing here should be presented as a measurement unless ``kind`` is
``"measured"``.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
import site
import sysconfig
from typing import Dict, List, Optional

def _resolve_examples_dir(source_dir: Optional[Path] = None,
                          data_dir: Optional[Path] = None,
                          user_data_dir: Optional[Path] = None) -> Path:
    """Find examples beside a checkout or in the installed data directory."""
    source_dir = (Path(__file__).resolve().parent.parent / "examples"
                  if source_dir is None else Path(source_dir))
    if source_dir.is_dir():
        return source_dir
    data_dir = Path(sysconfig.get_path("data")) if data_dir is None else Path(data_dir)
    installed = data_dir / "share" / "diffusor" / "examples"
    if installed.is_dir():
        return installed
    user_data_dir = (Path(site.getuserbase()) if user_data_dir is None
                     else Path(user_data_dir))
    user_installed = user_data_dir / "share" / "diffusor" / "examples"
    return user_installed if user_installed.is_dir() else installed


EXAMPLES_DIR = _resolve_examples_dir()


SYNTHETIC_STUDY = "Synthetic, made by Diffusor"


@dataclass(frozen=True)
class ExampleDataset:
    key: str
    name: str
    mineral: str
    species: str
    filename: str
    kind: str                      # 'measured' | 'synthetic'
    provenance: str                # where the numbers come from, in full
    citation: Optional[str]        # citation key, for measured data
    spec: Dict                     # ProfileSpec keyword arguments
    settings: Dict                 # suggested conditions and model settings
    expected: str = ""             # the known or published answer
    notes: str = ""
    # Where each condition in ``settings`` comes from, keyed "T", "P" and "fO2".
    # A value with no published source says so, so nobody mistakes a placeholder
    # for a measurement.
    sources: Dict[str, str] = field(default_factory=dict)
    # Where the example sits in the examples list: mineral, then study, then example.
    # ``study`` names the paper (or "Synthetic, made by Diffusor"); ``short`` is the
    # example's own name inside that study. Both fall back to values derived from the rest.
    study: str = ""
    short: str = ""

    @property
    def study_name(self) -> str:
        if self.study:
            return self.study
        if self.kind == "synthetic":
            return SYNTHETIC_STUDY
        from .references import get as _reference
        return _reference(self.citation).short()

    @property
    def short_name(self) -> str:
        return self.short or self.name.split(" (")[0]

    @property
    def path(self) -> Path:
        return EXAMPLES_DIR / self.filename

    @property
    def exists(self) -> bool:
        return self.path.exists()

    def provenance_banner(self) -> str:
        """The provenance, headed by a warning when the data are synthetic."""
        if self.kind == "synthetic":
            return f"SYNTHETIC DATA -- not a measurement\n{self.provenance}"
        return self.provenance


