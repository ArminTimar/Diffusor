def _validation_datasets():
    """Only source-configured cases become ready-to-run presets.

    The remaining measured traverses are distributed with a source manifest,
    rather than attaching invented default conditions to them.
    """
    import json
    manifest = EXAMPLES_DIR / "validation" / "manifest.json"
    if not manifest.exists():
        return []
    refits = EXAMPLES_DIR / "validation" / "results.json"
    refit_days = ({v["key"]: v["original_days"] for v in json.loads(refits.read_text(encoding="utf8"))}
                  if refits.exists() else {})
    result = []
    for r in json.loads(manifest.read_text(encoding="utf8")):
        s = r.get("setup")
        if r["study"] != "lynn2024" or not s or r["sample"] == "Ol 8":
            continue
        # Restrict the fit to the rows with archived initial and model values.
        import csv
        with (EXAMPLES_DIR / "validation" / r["file"]).open(encoding="utf8") as f:
            rows = [v for v in csv.DictReader(f) if v["Initial_Fo_mol"] and v["Published_model_Fo_mol"]]
