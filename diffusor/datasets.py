"""Bundled example datasets, one for every mineral.

Each entry records where the data came from.  Two kinds are shipped:

**measured**
    Real published data, transcribed from the paper's supplementary tables and
    cited.  Use these to check Diffusor against a published timescale.

**synthetic**
    Generated by Diffusor's own forward model with a known time, then given
    Gaussian noise.  The *conditions* are taken from a real published study of
    the same mineral so the numbers are realistic, but the profile itself is
    not a measurement.  Every synthetic entry says so explicitly, in this
    catalogue, in the loader and in the exported methods block.

Nothing here should be presented as a measurement unless ``kind`` is
``"measured"``.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional

EXAMPLES_DIR = Path(__file__).resolve().parent.parent / "examples"


@dataclass(frozen=True)
class ExampleDataset:
    key: str
    name: str
    mineral: str
    species: str
    filename: str
    kind: str                      # 'measured' | 'synthetic'
    provenance: str                # where the numbers come from, in full
    citation: Optional[str]        # citation key, for measured data
    spec: Dict                     # ProfileSpec keyword arguments
    settings: Dict                 # suggested conditions and model settings
    expected: str = ""             # the known or published answer
    notes: str = ""

    @property
    def path(self) -> Path:
        return EXAMPLES_DIR / self.filename

    @property
    def exists(self) -> bool:
        return self.path.exists()

    def provenance_banner(self) -> str:
        head = ("MEASURED DATA" if self.kind == "measured"
                else "SYNTHETIC DATA -- not a measurement")
        return f"{head}\n{self.provenance}"


