BY_KEY: Dict[str, ExampleDataset] = {d.key: d for d in DATASETS}


def for_mineral(mineral: str) -> List[ExampleDataset]:
    return [d for d in DATASETS if d.mineral == mineral]


def available() -> List[ExampleDataset]:
    return [d for d in DATASETS if d.exists]


def get(key: str) -> ExampleDataset:
    try:
        return BY_KEY[key]
    except KeyError as exc:
        raise KeyError(f"Unknown example dataset '{key}'. "
                       f"Available: {sorted(BY_KEY)}") from exc
