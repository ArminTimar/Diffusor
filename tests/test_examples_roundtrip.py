def test_olivine_example_recovers_120_days():
    T = 1150 + 273.15
    cond = Conditions(T_K=T, P_Pa=1.0e5, log_fo2_bar=log_fo2_from_delta("FMQ", -1.0, T),
                      X={"XFe": 0.15}, axis="c")
