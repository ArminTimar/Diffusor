def test_warning_fires_when_the_diffusion_length_eats_the_profile():
    """A profile whose plateaus have relaxed no longer satisfies the
    semi-infinite assumption, and the model must say so."""
    cond = Conditions(T_K=900 + 273.15, P_Pa=1.0e8, X={"XAn": 0.55})
    spec = ProfileSpec("Distance_um", "Mg_ppm", None, "Mg_err", mode="A")
    prof = build_profile(read_table(EXAMPLES / "plag_mg_an.csv"), spec)
    ic = guess_step_from_data(prof.x, prof.C)
    model = DiffusionModel(
        coefficient=get("plag_Mg_vanorman2014"), conditions=cond, initial=ic,
        geometry=Geometry("plane"), bc_left=dirichlet(ic.params["C_left"]),
        bc_right=dirichlet(ic.params["C_right"]), n_nodes=301,
        x_grid=np.linspace(prof.x.min(), prof.x.max(), 301))
    w = model.warnings(t_seconds=3000.0 * SEC_PER_YEAR)
    assert any("semi-infinite assumption" in s for s in w)


